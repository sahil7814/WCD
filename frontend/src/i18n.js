const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('wcd_language') === 'hi' ? 'hi' : 'en')

  useEffect(() => {
    localStorage.setItem('wcd_language', language)
    document.documentElement.lang = language
  }, [language])

  const value = useMemo(() => ({
    language,
    toggleLanguage: () => setLanguage(current => current === 'en' ? 'hi' : 'en'),
    t: key => translations[language][key] || translations.en[key] || key
  }), [language])

  return createElement(LanguageContext.Provider, { value }, children)
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}

export function bilingualLabel(english, hindi, language) {
  return language === 'hi' ? `${hindi} / ${english}` : `${english} / ${hindi}`
}
